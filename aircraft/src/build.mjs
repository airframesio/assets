// Builds the aircraft and balloon icon set from icons.mjs and classify.ts:
//   aircraft/svg/<key>.svg            one file per icon (32 x 32, with halo)
//   aircraft/aircraft-icons.json        keys, labels, colors, AIS codes, rotate flags
//   aircraft/aircraft-icons.ts          the module apps copy (icons, classifier, loaders)
//   aircraft/aircraft-icons.js          the same module as plain JavaScript
//   aircraft/sprite/aircraft[@2x].png   a Mapbox/MapLibre sprite sheet with its .json
//   aircraft/preview.png              every icon on light and dark backgrounds
//
// Usage: node aircraft/src/build.mjs   (needs Node 22.13+ and Playwright's Chromium for the PNGs)

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { stripTypeScriptTypes } from 'node:module';
import { ICONS, iconSvg } from './icons.mjs';
import { pathBounds } from '../../shared/extent.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..');
mkdirSync(join(out, 'svg'), { recursive: true });
mkdirSync(join(out, 'sprite'), { recursive: true });

const icons = ICONS.map((i) => ({
  key: i.key,
  label: i.label,
  group: i.group,
  color: i.color,
  stroke: i.stroke,
  rotate: i.rotate,
  scale: i.scale,
  span: pathBounds([...[i.body].flat().map((b) => (typeof b === 'string' ? b : b.d)), ...(i.extent ?? [])]).width,
  balloon: !!i.balloon,
  adsb: i.adsb ?? [],
  svg: iconSvg(i),
  template: iconSvg(i, { template: true }),
}));

for (const i of icons) writeFileSync(join(out, 'svg', `${i.key}.svg`), i.svg + '\n');

writeFileSync(
  join(out, 'aircraft-icons.json'),
  JSON.stringify(
    { version: 1, size: 32, icons: icons.map(({ svg, template, ...rest }) => ({ ...rest, file: `svg/${rest.key}.svg` })) },
    null,
    2,
  ) + '\n',
);

// ── The module apps copy ─────────────────────────────────────────────────────
const keys = icons.map((i) => `'${i.key}'`).join(' | ');
const data = icons
  .map(
    (i) =>
      `  {\n    key: '${i.key}',\n    label: ${JSON.stringify(i.label)},\n    group: ${JSON.stringify(i.group)},\n` +
      `    color: '${i.color}',\n    rotate: ${i.rotate},\n    scale: ${i.scale},\n    span: ${i.span},\n    balloon: ${i.balloon},\n` +
      `    adsb: ${JSON.stringify(i.adsb)},\n    svg: ${JSON.stringify(i.svg)},\n    template: ${JSON.stringify(i.template)},\n  },`,
  )
  .join('\n');

const header = `// Airframes aircraft and balloon map icons. GENERATED by airframesio/assets aircraft/src/build.mjs: do not edit here.
// Copy this file into an app as is; change the icons in airframesio/assets and copy it again.
/* eslint-disable */
`;

const ts =
  header +
  `
export type AircraftIconKey = ${keys};

export interface AircraftIcon {
  key: AircraftIconKey;
  /** Name for legends and tooltips (US English). */
  label: string;
  /** Legend section: Airliners, General aviation, Rotorcraft and other, Military, Balloons. */
  group: string;
  /** Default fill color (aircraft are usually recolored by the app). */
  color: string;
  /** True when the map should turn the icon by track or heading (it points north). */
  rotate: boolean;
  /** Size relative to a narrow-body airliner (1). */
  scale: number;
  /** The drawing's wingspan (width) on the 32 x 32 grid, for true-size drawing. */
  span: number;
  /** Balloon icons keep their own colors. */
  balloon: boolean;
  /** ADS-B emitter categories that select this icon when the type is unknown. */
  adsb: string[];
  /** A 32 x 32 SVG document with a light halo, in the default colors. */
  svg: string;
  /** The same SVG with {{fill}} and {{stroke}} tokens; use aircraftIconSvg() to recolor. */
  template: string;
}

export const AIRCRAFT_ICON_LIST: AircraftIcon[] = [
${data}
];

export const AIRCRAFT_ICONS = Object.fromEntries(AIRCRAFT_ICON_LIST.map((i) => [i.key, i])) as Record<AircraftIconKey, AircraftIcon>;

` +
  readFileSync(join(here, 'classify.ts'), 'utf8') +
  readFileSync(join(here, '..', '..', 'shared', 'sizing.ts'), 'utf8');

writeFileSync(join(out, 'aircraft-icons.ts'), ts);
writeFileSync(join(out, 'aircraft-icons.js'), stripTypeScriptTypes(ts, { mode: 'strip' }).replace(/\n{3,}/g, '\n\n'));

// ── PNG sprite sheets and the preview ────────────────────────────────────────
const require = createRequire(import.meta.url);
let chromium;
try {
  ({ chromium } = require('playwright'));
} catch {
  console.log('Playwright not found: wrote SVG, JSON and modules, skipped PNGs.');
  process.exit(0);
}

const browser = await chromium.launch();
const COLS = 8;
for (const ratio of [1, 2]) {
  const cell = 32;
  const rows = Math.ceil(icons.length / COLS);
  const page = await browser.newPage({ viewport: { width: COLS * cell, height: rows * cell }, deviceScaleFactor: ratio });
  const index = {};
  const html = icons
    .map((i, n) => {
      const x = (n % COLS) * cell;
      const y = Math.floor(n / COLS) * cell;
      index[i.key] = { x: x * ratio, y: y * ratio, width: cell * ratio, height: cell * ratio, pixelRatio: ratio };
      return `<div style="position:absolute;left:${x}px;top:${y}px">${i.svg}</div>`;
    })
    .join('');
  await page.setContent(`<body style="margin:0;background:transparent">${html}</body>`);
  const name = ratio === 1 ? 'aircraft' : 'aircraft@2x';
  await page.screenshot({ path: join(out, 'sprite', `${name}.png`), omitBackground: true });
  writeFileSync(join(out, 'sprite', `${name}.json`), JSON.stringify(index, null, 2) + '\n');
  await page.close();
}

const groups = [...new Set(icons.map((i) => i.group))];
const sheet = (bg, fg) =>
  `<section style="background:${bg};color:${fg};padding:20px 24px">` +
  groups
    .map(
      (g) =>
        `<h2>${g}</h2><div class="grid">` +
        icons
          .filter((i) => i.group === g)
          .map(
            (i) =>
              `<figure><div class="pair">${i.svg.replace('width="32" height="32"', `width="${Math.round(48 * (i.scale ?? 1))}" height="${Math.round(48 * (i.scale ?? 1))}"`)}` +
              `<span style="transform:rotate(${i.rotate ? 40 : 0}deg)">${i.svg.replace('width="32" height="32"', 'width="24" height="24"')}</span></div>` +
              `<figcaption>${i.label}</figcaption></figure>`,
          )
          .join('') +
        `</div>`,
    )
    .join('') +
  `</section>`;
const page = await browser.newPage({ viewport: { width: 1400, height: 800 }, deviceScaleFactor: 2 });
await page.setContent(
  `<style>body{margin:0;background:#18212c;font:13px/1.3 -apple-system,Segoe UI,Helvetica,Arial,sans-serif}h2{font-size:14px;margin:14px 0 8px;opacity:.75;font-weight:600}
  .grid{display:grid;grid-template-columns:repeat(6,1fr);gap:10px}figure{margin:0;text-align:center}
  .pair{display:flex;gap:10px;align-items:center;justify-content:center;height:64px}.pair span{display:inline-flex}
  figcaption{font-size:12px;opacity:.8;margin-top:4px}</style>
  <div style="display:grid;grid-template-columns:1fr 1fr">${sheet('#eef1f4', '#1d2530')}${sheet('#18212c', '#e6ebf0')}</div>`,
);
await page.locator('body > div').screenshot({ path: join(out, 'preview.png') });
await browser.close();
console.log(`Built ${icons.length} icons.`);
